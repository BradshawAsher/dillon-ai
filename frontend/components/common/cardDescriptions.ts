export function getCardDescription(cardId: string): CardDescription {
    if (CARD_DESCRIPTIONS[cardId]) {
        return CARD_DESCRIPTIONS[cardId]
    }
    // Formatted fallback if not explicitly registered
    const formattedTitle = cardId
        .replace(/^[a-z]+-/, '')
        .split('-')
        .map(w => w.charAt(0).toUpperCase() + w.slice(1))
        .join(' ')

    return {
        title: formattedTitle || 'Deal Diligence Card',
        category: 'Financial Diligence',
        whatItIs: 'Specialized M&A financial and operational evaluation component analyzing extracted deal metrics, covenants, and valuation parameters.',
        calculation: 'Synthesized from verified deal room documents, tax returns, and deterministic underwriting formulas.',
        diligenceImpact: 'Evaluates acquisition feasibility, debt solvency, and risk-adjusted valuation.',
        benchmarkOrTarget: 'Institutional PE standards',
    }
}
